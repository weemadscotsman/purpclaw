'use strict';
/**
 * Parity authority check.
 *
 * There is exactly ONE authoritative parity roadmap: docs/parity/CANONICAL_PARITY_PRIORITY.md.
 * Every other parity document is historical input. This gate keeps it that way.
 *
 * FAILS (exit 1) when:
 *   a. a parity-named doc neither IS the canonical roadmap nor points at it.
 *      Candidate = file whose BASENAME contains "parity" (case-insensitive) with
 *      extension .md or .json, outside the excluded dirs below. "Points at it"
 *      means the file text contains the string "CANONICAL_PARITY_PRIORITY.md"
 *      (covers the markdown banner link in .md files and the "_superseded"
 *      field in .json files).
 *   b. AGENT.md no longer contains the literal path
 *      "docs/parity/CANONICAL_PARITY_PRIORITY.md".
 *   c. more than one document carries the AUTHORITY MARKER. The marker is
 *      defined precisely as the literal string:  Status: **CANONICAL**
 *      (case-sensitive, exactly that spelling, including the bold asterisks).
 *      Only docs/parity/CANONICAL_PARITY_PRIORITY.md may carry it. Zero
 *      occurrences also fails — the canonical doc must keep declaring itself.
 *      Marker scanning covers .md files under the same walk/exclusion rules.
 *
 * EXCLUDED DIRS (throwaway copies, build output, generated data — not repo docs):
 *   .git, node_modules, vendor, agent_work, .omnicode, .next, dist, build,
 *   coverage, public, and any directory whose name starts with ".tmp-".
 *   `public/` is excluded because the parity JSON under it is regenerated by
 *   scripts/audit-parity.mjs and scripts/audit-showcase-claims.mjs — a banner
 *   written there would be clobbered on the next run.
 *
 * Run: npm run parity:check   (also invoked by npm run docs:gate)
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const CANON_REL = 'docs/parity/CANONICAL_PARITY_PRIORITY.md';
const CANON_BASENAME = 'CANONICAL_PARITY_PRIORITY.md';
const AUTHORITY_MARKER = 'Status: **CANONICAL**';

const EXCLUDE_DIRS = new Set([
  '.git', 'node_modules', 'vendor', 'agent_work', '.omnicode',
  '.next', 'dist', 'build', 'coverage', 'public',
]);

function walk(dir, out = []) {
  let entries;
  try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch { return out; }
  for (const e of entries) {
    if (e.isDirectory()) {
      if (EXCLUDE_DIRS.has(e.name) || e.name.startsWith('.tmp-')) continue;
      walk(path.join(dir, e.name), out);
    } else if (e.isFile()) {
      out.push(path.join(dir, e.name));
    }
  }
  return out;
}

const errors = [];
const files = walk(ROOT);
const rel = (f) => path.relative(ROOT, f).replace(/\\/g, '/');

// ── a. every parity-named doc must point at the canonical roadmap ────────────
let checked = 0;
for (const abs of files) {
  const base = path.basename(abs);
  if (!/parity/i.test(base)) continue;
  if (!/\.(md|json)$/i.test(base)) continue;
  if (rel(abs) === CANON_REL) continue;
  checked++;
  const text = fs.readFileSync(abs, 'utf8');
  if (!text.includes(CANON_BASENAME)) {
    errors.push(`${rel(abs)}: parity doc does not point at ${CANON_REL}`);
  }
}

if (!fs.existsSync(path.join(ROOT, CANON_REL))) {
  errors.push(`canonical parity roadmap missing: ${CANON_REL}`);
}

// ── b. AGENT.md must keep the authority pointer ──────────────────────────────
const agentMd = path.join(ROOT, 'AGENT.md');
if (!fs.existsSync(agentMd)) {
  errors.push('AGENT.md: missing');
} else if (!fs.readFileSync(agentMd, 'utf8').includes(CANON_REL)) {
  errors.push(`AGENT.md: missing canonical authority pointer to ${CANON_REL}`);
}

// ── c. exactly one document may claim authority ──────────────────────────────
const claimants = [];
for (const abs of files) {
  if (!/\.md$/i.test(abs)) continue;
  if (fs.readFileSync(abs, 'utf8').includes(AUTHORITY_MARKER)) claimants.push(rel(abs));
}
if (claimants.length !== 1 || claimants[0] !== CANON_REL) {
  errors.push(
    `authority marker "${AUTHORITY_MARKER}" found in ${claimants.length} file(s) ` +
    `[${claimants.join(', ')}] — expected exactly 1: ${CANON_REL}`
  );
}

// ── Report ───────────────────────────────────────────────────────────────────
console.log('=== PARITY AUTHORITY CHECK ===');
console.log(`Canonical: ${CANON_REL}`);
console.log(`Superseded parity docs checked: ${checked}`);
console.log(`Authority claimants: ${claimants.length} (${claimants.join(', ') || 'none'})`);

if (errors.length) {
  console.error(`\nERRORS (${errors.length}):`);
  errors.forEach(e => console.error('  ' + e));
  console.error('\nPARITY AUTHORITY CHECK FAILED');
  process.exit(1);
}
console.log('\nPARITY AUTHORITY CHECK PASSED');
