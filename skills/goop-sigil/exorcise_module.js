if (require.main === module) {
  const args = process.argv.slice(2);
  const pathIdx = args.indexOf('--path');
  const pathArg = args.find(a => a.startsWith('--path='))?.split('=')[1] || (pathIdx !== -1 ? args[pathIdx + 1] : null);
  
  const strategyIdx = args.indexOf('--strategy');
  const strategy = args.find(a => a.startsWith('--strategy='))?.split('=')[1] || (strategyIdx !== -1 ? args[strategyIdx + 1] : 'split_by_domain');

  if (!pathArg) {
    console.error('\x1b[31m[GOOP-SIGIL] Error: Missing --path target to exorcise.\x1b[0m');
    console.log('Usage: node skills/goop-sigil/exorcise_module.js --path <file_path> --strategy <strategy>');
    process.exit(1);
  }

  // Backup original file before modification if it exists
  const absolutePath = path.resolve(pathArg);
  if (fs.existsSync(absolutePath)) {
    const backupPath = absolutePath + '.exorcised.bak';
    fs.copyFileSync(absolutePath, backupPath);
  }

  // Smart dynamic classifier for split_by_domain if map not provided
  const domainMap = {};
  const deadExports = [];
  if (strategy === 'split_by_domain' || strategy === 'full_exorcism') {
    try {
      const code = fs.readFileSync(absolutePath, 'utf8');
      const ast = parser.parse(code, { sourceType: 'module', plugins: ['typescript', 'jsx'] });
      traverse(ast, {
        ClassDeclaration(p) {
          p.node.body.body.forEach(method => {
            if (method.type === 'ClassMethod' || method.type === 'MethodDefinition') {
              const name = method.key.name;
              if (name.includes('watch') || name.includes('vent') || name.includes('gate') || name.includes('core')) {
                domainMap[name] = 'watcher';
              } else if (name.includes('telemetry') || name.includes('ping') || name.includes('record') || name.includes('log')) {
                domainMap[name] = 'telemetry';
              } else {
                domainMap[name] = 'misc';
              }
            }
          });
        },
        ExportNamedDeclaration(p) {
          p.node.specifiers.forEach(spec => {
            if (spec.exported.name.includes('DEAD')) {
              deadExports.push(spec.exported.name);
            }
          });
        },
        VariableDeclaration(p) {
          p.node.declarations.forEach(decl => {
            if (decl.id.name && decl.id.name.includes('DEAD')) {
              deadExports.push(decl.id.name);
            }
          });
        }
      });
    } catch (e) {
      // Fallback gracefully
    }
  }

  const result = exorciseModule({
    path: pathArg,
    strategy,
    options: {
      domainMap,
      cycles: [],
      deadExports: deadExports.length ? deadExports : ['DEAD_BLESSING']
    }
  });

  if (result.success) {
    console.log(`\n\x1b[35m✨ [GOOP-SIGIL EXORCISM INITIATED]\x1b[0m`);
    console.log(`   Target:    \x1b[33m${pathArg}\x1b[0m`);
    console.log(`   Strategy:  \x1b[37m${strategy}\x1b[0m`);
    console.log(`\n\x1b[32m🔥 EXORCISM COMPLETE.\x1b[0m`);
    console.log(`   ${result.message}`);
    if (result.generatedFiles && result.generatedFiles.length > 0) {
      console.log(`   New files written to ./exorcised/`);
      result.generatedFiles.forEach(f => console.log(`    ↳ ${path.relative(process.cwd(), f)}`));
    }
    console.log(`\n\x1b[36m"The watcher no longer watches everything. Darren can rest. GOOP flows. Nonna approves. 🤌"\x1b[0m\n`);
  } else {
    console.error(`\x1b[31m❌ EXORCISM FAILED:\x1b[0m ${result.message}`);
    process.exit(1);
  }
}

