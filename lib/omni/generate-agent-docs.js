function readJson(path) {
  try { return JSON.parse(fs.readFileSync(path, 'utf8')); } catch { return null; }
}

function renderActionQueue(reg) {
  if (!reg || !Array.isArray(reg.features)) return '_no registry loaded_';
  const lines = [];
  for (const f of reg.features.filter(x => x.actionRequired).slice(0, 25)) {
    lines.push(`- **${f.id}** — state: \`${f.state}\` — ${f.note || f.reasons?.join('; ') || 'verify in next cycle'}`);
  }
  return lines.join('\n');
}

function renderPendingDecisions(reg) {
  if (!reg || !Array.isArray(reg.features)) return '_no registry loaded_';
  const decisions = [];
  for (const f of reg.features) {
    if (f.state === 'planned' || f.state === 'missing-wiring' || f.state === 'failing') {
      decisions.push(`- \`${f.id}\` (${f.state}) — ${f.note || 'operator must decide: wire it, defer it, or operator-disable it explicitly'}`);
    }
  }
  return decisions.join('\n') || '_none_';
}

function main() {
  const args = process.argv.slice(2);
  let inPath = null;
  let registryPath = null;
  let outDir = null;
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--in' && args[i+1]) { inPath = args[i+1]; i++; }
    else if (args[i] === '--registry' && args[i+1]) { registryPath = args[i+1]; i++; }
    else if (args[i] === '--out' && args[i+1]) { outDir = args[i+1]; i++; }
  }
  if (!inPath) inPath = path.join(process.cwd(), 'agent_work', 'omni', 'truth-snapshot.json');
  if (!registryPath) registryPath = path.join(process.cwd(), 'agent_work', 'omni', 'feature-registry.json');
  if (!outDir) outDir = path.join(process.cwd(), 'docs');

  const snap = readJson(inPath);
  const reg = readJson(registryPath);
  const generatedAt = new Date().toISOString();
  const featuresCount = reg?.features?.length || 0;
  const actionRequiredCount = reg?.features?.filter(f => f.actionRequired).length || 0;

  // Use a simple template substitution: \${var} -> value. Avoids a
  // // template-engine dependency.
  function fillTemplate(tpl) {
    return tpl
      .replace(/\$\{generatedAt\}/g, generatedAt)
      .replace(/\$\{schemaVersion\}/g, SCHEMA_VERSION)
      .replace(/\$\{snapshotSource\}/g, inPath)
      .replace(/\$\{registrySource\}/g, registryPath)
      .replace(/\$\{featuresCount\}/g, featuresCount)
      .replace(/\$\{actionRequiredCount\}/g, actionRequiredCount)
      .replace(/\$\{actionQueue\}/g, renderActionQueue(reg))
      .replace(/\$\{pendingDecisions\}/g, renderPendingDecisions(reg));
  }

  fs.mkdirSync(outDir, { recursive: true });
  const agentPath = path.join(outDir, 'AGENT.md');
  const loopPath = path.join(outDir, 'LOOP.md');
  fs.writeFileSync(agentPath, fillTemplate(AGENT_TEMPLATE));
  fs.writeFileSync(loopPath, fillTemplate(LOOP_TEMPLATE));
  console.log(`OMNI-SURGEON Phase Four — AGENT.md / LOOP.md generator`);
  console.log(`  in:     ${inPath}`);
  console.log(`  reg:    ${registryPath}`);
  console.log(`  out:    ${outDir}`);
  console.log(`  agent:  ${agentPath}`);
  console.log(`  loop:   ${loopPath}`);
  console.log(`  features: ${featuresCount}  actionRequired: ${actionRequiredCount}`);
}

if (require.main === module) main();
module.exports = { main, renderActionQueue, renderPendingDecisions, AGENT_TEMPLATE, LOOP_TEMPLATE, SCHEMA_VERSION };
